const BCP47_BY_CODE: Record<string, string> = {
  "pt-br": "pt-BR",
  "pt-pt": "pt-PT",
  "zh-cn": "zh-CN",
  "zh-tw": "zh-TW",
}

export function subtitleLanguageName(code: string, locale?: string): string {
  const entry = SUBTITLE_LANGUAGES.find((language) => language.code === code)
  const fallback = entry ? entry.name : code
  try {
    const display = new Intl.DisplayNames([locale || "en"], { type: "language" })
    return display.of(BCP47_BY_CODE[code] || code) || fallback
  } catch {
    return fallback
  }
}
